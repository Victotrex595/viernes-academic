def get_spanish_month_year() -> str:
    now = datetime.now()
    return f"{SPANISH_MONTHS[now.month]} {now.year}"


def safe_folder_name(name: str) -> str:
    clean = re.sub(r'[<>:"/\\|?*]', "", name).strip(" .")
    return re.sub(r"\s+", "_", clean)[:65] or "General"


def _add_formatted_runs(
    paragraph,
    text: str,
    font_name: str = "Arial",
    font_size_pt: float = 12.0,
    force_bold: bool = False,
) -> None:
    """Parses **bold** segments in markdown line and adds runs with explicit Arial font formatting."""
    parts = re.split(r"(\*\*.*?\*\*)", text)
    for part in parts:
        if not part:
            continue
        if part.startswith("**") and part.endswith("**") and len(part) > 4:
            run = paragraph.add_run(part[2:-2])
            run.bold = True
        else:
            run = paragraph.add_run(part)
            if force_bold:
                run.bold = True
        run.font.name = font_name
        run.font.size = Pt(font_size_pt)
        run.font.color.rgb = RGBColor(0, 0, 0)


def _direct_p_text_nodes(p_elem):
    """Returns <w:t> nodes that belong to this <w:p> without descending into nested <w:txbxContent> or inner <w:p>."""
    result = []

    def _walk(node):
        for child in node:
            if child.tag.endswith("}p") or child.tag.endswith("}txbxContent") or child.tag.endswith("}textbox"):
                continue
            if child.tag.endswith("}t"):
                result.append(child)
            else:
                _walk(child)

    _walk(p_elem)
    return result


def _replace_placeholders_in_xml_body(doc: Document, replacements: Dict[str, str]) -> None:
    """Replaces placeholders across all paragraphs, tables, and floating Word textboxes without merging separate paragraphs."""
    for elem in doc.element.body.iter():
        if not elem.tag.endswith("}p"):
            continue
        t_nodes = _direct_p_text_nodes(elem)
        if not t_nodes:
            continue
        full_text = "".join(t.text or "" for t in t_nodes)
        modified = full_text
        for placeholder, val in replacements.items():
            if placeholder in modified:
                modified = modified.replace(placeholder, val)
        if modified != full_text:
            # Put the replaced text in the first <w:t> node of THIS paragraph and clear remaining split nodes in THIS paragraph
            t_nodes[0].text = modified
            for extra_t in t_nodes[1:]:
                extra_t.text = ""


def _strip_duplicate_ai_cover(markdown_body: str) -> str:
    """Removes any fake text cover page or Table of Contents generated by the AI when using the official PSM cover template."""
    lines = markdown_body.splitlines()
    # Look for the first real content heading (e.g. INTRODUCCIÓN or 1. PLANTEAMIENTO) after any fake cover / CONTENIDO block
    intro_indices = []
    for idx, raw in enumerate(lines):
        clean = re.sub(r"^[#\*\s\d\.\-]+", "", raw.strip()).upper()
        if clean in ("INTRODUCCIÓN", "INTRODUCCION") or clean.startswith("INTRODUCCIÓN") or clean.startswith("INTRODUCCION"):
            intro_indices.append(idx)

    if intro_indices:
        # If there are two "INTRODUCCIÓN" occurrences (one in CONTENIDO index and one for the real section), pick the last one in the top half
        chosen_idx = intro_indices[-1] if len(intro_indices) > 1 and intro_indices[-1] < max(45, len(lines) // 2) else intro_indices[0]
        return "\n".join(["# INTRODUCCIÓN"] + lines[chosen_idx + 1 :])

    # Otherwise strip known fake cover lines at the top
    cleaned_lines = []
    skipping_cover = True
    cover_markers = (
        "república bolivariana",
        "republica bolivariana",
        "ministerio del poder",
        "instituto universitario politécnico",
        "instituto universitario politecnico",
        "santiago mariño",
        "extensión",
        "extension",
        "escuela de ingeniería",
        "insertar logo",
        "bachiller:",
        "alumno:",
        "estudiante:",
        "c.i.:",
        "cédula:",
        "sección:",
        "seccion:",
        "[ciudad]",
        "portada",
    )
    for raw in lines:
        low = raw.strip().lower()
        if skipping_cover:
            if not low or any(m in low for m in cover_markers):
                continue
            skipping_cover = False
        cleaned_lines.append(raw)
    return "\n".join(cleaned_lines)


def _append_markdown_body_to_doc(doc: Document, markdown_body: str) -> None:
    """Appends markdown paragraphs using explicit run/paragraph formatting (never relies on missing Word styles like 'List Bullet' or 'Heading 1')."""
    for raw_line in markdown_body.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("---"):
            continue

        # Headings: Arial 14, Bold, Centered (Normas PSM)
        if line.startswith("#"):
            clean_heading = re.sub(r"^#+\s*", "", line).replace("**", "").strip()
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_before = Pt(14)
            p.paragraph_format.space_after = Pt(8)
            p.paragraph_format.line_spacing = 1.5
            _add_formatted_runs(p, clean_heading, font_name="Arial", font_size_pt=14.0, force_bold=True)
        # Bullet list items: Arial 12, Justified, Left indent
        elif line.startswith(("- ", "* ", "• ")):
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            p.paragraph_format.left_indent = Cm(1.0)
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.line_spacing = 1.5
            _add_formatted_runs(p, "• " + line[2:].strip(), font_name="Arial", font_size_pt=12.0)
        # Numbered list items: Arial 12, Justified, Left indent
        elif re.match(r"^\d+[\.\)]\s+", line):
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            p.paragraph_format.left_indent = Cm(1.0)
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.line_spacing = 1.5
            _add_formatted_runs(p, line, font_name="Arial", font_size_pt=12.0)
        # Normal body paragraphs: Arial 12, Justified, 1.5 line spacing, first-line indent
        else:
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            p.paragraph_format.first_line_indent = Cm(1.0)
            p.paragraph_format.space_after = Pt(8)
            p.paragraph_format.line_spacing = 1.5
            _add_formatted_runs(p, line, font_name="Arial", font_size_pt=12.0)


def write_markdown_to_docx(
    filepath: str,
    title: str,
    subtitle: str,
    markdown_body: str,
    use_psm_template: bool = False,
    teacher_name: str = "Docente de la Cátedra",
) -> str:
    os.makedirs(os.path.dirname(filepath), exist_ok=True)

    if use_psm_template and os.path.exists(PSM_TEMPLATE_PATH):
        doc = Document(PSM_TEMPLATE_PATH)
        replacements = {
            "[TEMA]": title.strip(),
            "[NOMBRE Y APELLIDO DEL DOCENTE]": teacher_name.strip(),
            "[NOMBRE DE LA MATERIA ]": subtitle.strip(),
            "[NOMBRE DE LA MATERIA]": subtitle.strip(),
            "[MES Y AÑO]": get_spanish_month_year(),
        }
        _replace_placeholders_in_xml_body(doc, replacements)
        clean_body = _strip_duplicate_ai_cover(markdown_body)
        doc.add_page_break()
        _append_markdown_body_to_doc(doc, clean_body)
        doc.save(filepath)
        return filepath

    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Arial"
    style.font.size = Pt(11)

    h_title = doc.add_heading(title, level=0)
    h_title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    p_meta = doc.add_paragraph()
    p_meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r_meta = p_meta.add_run(
        f"{subtitle}  |  Generado: {datetime.now().strftime('%d/%m/%Y %H:%M')}"
    )
    r_meta.italic = True
    r_meta.font.size = Pt(9.5)
    r_meta.font.color.rgb = RGBColor(100, 100, 100)

    doc.add_paragraph("─" * 55)
    _append_markdown_body_to_doc(doc, markdown_body)
    doc.save(filepath)
    return filepath


def create_four_pillars_docx_bundle(
    course_name: str,
    assignment_title: str,
    pillars_content: Dict[str, str],
) -> Dict[str, str]:
    """Creates 01_Preparar.docx, 02_Comprender.docx, 03_Comprobar.docx, 04_Consolidar.docx locally."""
    course_folder = safe_folder_name(course_name)
    task_folder = safe_folder_name(assignment_title)
    base_path = os.path.join(GENERATED_DOCS_DIR, course_folder, task_folder)
    os.makedirs(base_path, exist_ok=True)

    pillar_titles = {
        "01_Preparar": "Pilar 1: PREPARAR (Glosario, Prerrequisitos y Preguntas Detonantes)",
        "02_Comprender": "Pilar 2: COMPRENDER (Desarrollo Profundo, Analogías y Paso a Paso)",
        "03_Comprobar": "Pilar 3: COMPROBAR (Autoevaluación, Ejercicios Resueltos y Casos)",
        "04_Consolidar": "Pilar 4: CONSOLIDAR (Resumen Ejecutivo, Cuadros Sinópticos y Flashcards)",
    }

    saved_files: Dict[str, str] = {}
    for key, doc_title in pillar_titles.items():
        body = pillars_content.get(key, "Contenido no disponible.")
        file_path = os.path.join(base_path, f"{key}.docx")
        write_markdown_to_docx(
            filepath=file_path,
            title=f"{assignment_title} — {doc_title}",
            subtitle=course_name,
            markdown_body=body,
            use_psm_template=False,
        )
        saved_files[key] = file_path

    return saved_files


def create_resolution_docx(
    course_name: str,
    assignment_title: str,
    task_mode: str,
    resolution_markdown: str,
    is_external: bool = False,
    teacher_name: Optional[str] = None,
    avoid_overwrite: bool = True,
) -> str:
    course_folder = safe_folder_name(course_name)
    task_folder = safe_folder_name(assignment_title)
    base_path = os.path.join(GENERATED_DOCS_DIR, course_folder, task_folder)
    os.makedirs(base_path, exist_ok=True)

    base_filename = f"Resolucion_{task_mode.capitalize()}_Borrador"
    file_path = os.path.join(base_path, f"{base_filename}.docx")
    if avoid_overwrite and os.path.exists(file_path):
        version = 2
        while os.path.exists(os.path.join(base_path, f"{base_filename}_v{version}.docx")):
            version += 1
        file_path = os.path.join(base_path, f"{base_filename}_v{version}.docx")

    # Use the user's official PSM Word Template for digital works (and PSM works)
    use_template = (task_mode == "digital") and os.path.exists(PSM_TEMPLATE_PATH)

    write_markdown_to_docx(
        filepath=file_path,
        title=assignment_title,
        subtitle=course_name,
        markdown_body=resolution_markdown,
        use_psm_template=use_template,
        teacher_name=teacher_name or "Docente de la Cátedra",
    )
    return file_path
